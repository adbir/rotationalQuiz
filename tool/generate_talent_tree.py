#!/usr/bin/env python3
"""Generates a Dart talent tree table from SimulationCraft's trait data.

The table lists every talent node of one class in the order Blizzard's
in-game talent export strings use (ascending node id, entries in SimC's
selection order), which is what `TalentStringCodec` needs to decode them.

Usage:
  python3 -I tool/generate_talent_tree.py --class-id 7 --name shaman \
      > lib/domain/talents/generated/shaman_talent_tree.g.dart
  dart format lib/domain/talents/generated

By default the trait data is downloaded from the SimC `midnight` branch;
pass --trait-data to use a local copy of engine/dbc/generated/trait_data.inc.
"""
import argparse
import re
import sys
import urllib.request
from collections import OrderedDict

DEFAULT_URL = (
    "https://raw.githubusercontent.com/simulationcraft/simc/midnight/"
    "engine/dbc/generated/trait_data.inc"
)

ROW = re.compile(
    r'\{\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),'
    r'\s*(\d+),\s*(\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*"((?:[^"\\]|\\.)*)",'
    r'\s*\{([^}]*)\},\s*\{([^}]*)\},\s*(\d+),\s*(\d+)\s*\}'
)


def tokenize(name: str) -> str:
    """Mirrors SimC's util::tokenize for talent names."""
    name = name.lower().replace("'", "")
    name = re.sub(r"[^a-z0-9_ ]", "", name.replace("-", "_").replace(":", ""))
    return re.sub(r"_+", "_", name.strip().replace(" ", "_"))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--class-id", type=int, required=True)
    parser.add_argument("--name", required=True)
    parser.add_argument("--trait-data")
    args = parser.parse_args()

    if args.trait_data:
        source = open(args.trait_data, encoding="utf-8").read()
    else:
        source = urllib.request.urlopen(DEFAULT_URL).read().decode("utf-8")
    build = re.search(r"wow build ([\d.]+)", source)
    # Only the live (non-PTR) table: stop at the first array terminator.
    live = source.split("} };", 1)[0]

    nodes: "OrderedDict[int, list]" = OrderedDict()
    rows = [m.groups() for m in ROW.finditer(live)]
    # SimC iterates trees INVALID..SELECTION; the generated array is already
    # sorted by (tree, class, node, selection index).
    for tree in range(0, 5):
        for g in rows:
            if int(g[0]) != tree or int(g[1]) != args.class_id:
                continue
            node_id = int(g[3])
            nodes.setdefault(node_id, []).append(g)

    out = sys.stdout
    out.write("// GENERATED by tool/generate_talent_tree.py. Do not edit by hand.\n")
    out.write(f"// Source: SimulationCraft trait_data.inc, WoW build {build.group(1) if build else '?'}.\n\n")
    out.write("import '../talent_tree.dart';\n\n")
    out.write(f"const {args.name}TalentTree = TalentTree(\n")
    out.write(f"  classId: {args.class_id},\n")
    out.write(f"  build: '{build.group(1) if build else ''}',\n")
    out.write("  nodes: [\n")
    for node_id in sorted(nodes):
        entries = nodes[node_id]
        node_type = int(entries[0][17])
        out.write(f"    TalentNode({node_id}, {node_type}, [\n")
        for g in entries:
            specs = [int(s) for s in g[14].split(",") if int(s) != 0]
            name = g[13].replace("\\\"", "\"").replace("'", "\\'")
            out.write(
                f"      TalentEntry({int(g[2])}, '{name}', '{tokenize(g[13])}', "
                f"tree: {int(g[0])}, maxRanks: {int(g[4])}, "
                f"specs: {specs}, subTree: {int(g[16])}),\n"
            )
        out.write("    ]),\n")
    out.write("  ],\n);\n")


if __name__ == "__main__":
    main()
